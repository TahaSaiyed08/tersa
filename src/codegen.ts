// Tersa -> Python code generator.
import type * as A from "./ast.js";
import type { CheckResult, FnSig } from "./checker.js";
import { pyId, pyAttr, exprText } from "./checker.js";
import { BUILTINS } from "./builtins.js";
import { prune, type Type } from "./types.js";
import { TersaError } from "./diagnostics.js";

export const VERSION = "0.1.0";

type Dest = { k: "none" } | { k: "return" } | { k: "assign"; target: string };
const NONE: Dest = { k: "none" };
const RETURN: Dest = { k: "return" };

export interface GenOptions { tests: boolean; srcLabel: string }

export function generate(prog: A.Program, chk: CheckResult, opts: GenOptions): string {
  return new Gen(prog, chk, opts).run();
}

class Gen {
  lines: string[] = [];
  map: number[] = [0];
  ind = 0;
  tmp = 0;
  curLine = 0;
  lambdaDepth = 0;

  constructor(private prog: A.Program, private chk: CheckResult, private opts: GenOptions) {}

  emit(text: string, line = this.curLine) {
    this.lines.push("    ".repeat(this.ind) + text);
    this.map.push(line);
  }
  fresh(base = "_t"): string { return `${base}${++this.tmp}`; }

  fail(pos: A.Pos, msg: string, hint?: string): never {
    throw new TersaError({ code: "E900", message: msg, file: this.prog.file, line: pos.line, col: pos.col, hint });
  }

  run(): string {
    const decls = this.prog.decls;
    this.emit(`# Generated by Tersa ${VERSION} from ${this.opts.srcLabel}. Do not edit.`, 0);
    this.emit("@@LINEMAP@@", 0); // replaced at the end: must be defined before any code that can fail
    this.emit("import tersa_rt as _rt", 0);
    for (const im of this.chk.imports) {
      if (im.alias) this.emit(`import ${im.pyModule} as ${im.alias}`, 0);
      else if (im.names?.length) this.emit(`from ${im.pyModule} import ${im.names.join(", ")}`, 0);
    }
    for (const ex of this.chk.externs) this.emit(`import ${ex.module} as ${ex.alias}`, 0);

    for (const d of decls) {
      this.curLine = d.line;
      if (d.k === "record") this.emitRecord(d);
      else if (d.k === "sum") this.emitSum(d);
    }
    for (const d of decls) {
      if (d.k !== "fn") continue;
      this.curLine = d.line;
      this.emitFn(d);
      if (d.owner) {
        const sig: FnSig = (d as any).sig;
        if (sig) this.emit(`${pyId(d.owner)}.${pyAttr(d.name)} = ${sig.pyName}`);
      }
    }
    if (this.opts.tests) {
      let n = 0;
      for (const d of decls) {
        if (d.k !== "test") continue;
        this.curLine = d.line;
        const fname = `_ts_test_${++n}`;
        this.emit("");
        this.emit(`def ${fname}():`);
        this.ind++;
        const globals: Set<string> | undefined = (d as any).globals;
        if (globals?.size) this.emit(`global ${[...globals].join(", ")}`);
        this.block(d.body, NONE);
        this.ind--;
        this.emit(`_rt.register_test(${JSON.stringify(d.name)}, ${fname}, ${JSON.stringify(this.opts.srcLabel)}, ${d.line})`);
      }
    }
    let first = true;
    for (const d of decls) {
      if (d.k !== "stmt") continue;
      if (first) { this.emit("", d.line); first = false; }
      this.stmt(d.stmt);
    }
    const idx = this.lines.indexOf("@@LINEMAP@@");
    this.lines[idx] = `_TS_SRC = ${JSON.stringify(this.opts.srcLabel)}; _TS_LINES = [${this.map.join(",")},0]`;
    return this.lines.join("\n") + "\n";
  }

  // ---------- types ----------
  defaultExpr(e: A.Expr): string {
    return isLiteral(e) ? this.ex(e) : `_rt.field(default_factory=lambda: ${this.ex(e)})`;
  }

  emitRecord(d: Extract<A.Decl, { k: "record" }>) {
    const frozen = !d.fields.some((f) => f.mutable);
    this.emit("");
    this.emit(`@_rt.dataclass(frozen=${frozen ? "True" : "False"})`);
    this.emit(`class ${pyId(d.name)}:`);
    this.ind++;
    if (!d.fields.length) this.emit("pass");
    for (const f of d.fields) {
      this.curLine = f.pos.line;
      this.emit(`${pyAttr(f.name)}: object${f.default ? " = " + this.defaultExpr(f.default) : ""}`);
    }
    this.ind--;
  }

  emitSum(d: Extract<A.Decl, { k: "sum" }>) {
    const base = pyId(d.name);
    this.emit("");
    this.emit(`class ${base}:`);
    this.emit("    pass");
    for (const v of d.variants) {
      this.curLine = v.pos.line;
      this.emit(`@_rt.dataclass(frozen=True)`);
      this.emit(`class ${pyId(v.name)}(${base}):`);
      this.ind++;
      this.emit("_tsa_variant = True");
      for (const f of v.fields) this.emit(`${pyAttr(f.name)}: object${f.default ? " = " + this.defaultExpr(f.default) : ""}`);
      this.ind--;
    }
  }

  // ---------- functions ----------
  emitFn(d: A.FnDecl) {
    const sig: FnSig | undefined = (d as any).sig;
    if (!sig) return;
    this.curLine = d.line;
    const params: string[] = d.owner ? ["self"] : [];
    const lateDefaults: [string, A.Expr][] = [];
    for (const p of d.params) {
      const name = pyId(p.name);
      if (!p.default) params.push(name);
      else if (isLiteral(p.default)) params.push(`${name}=${this.ex(p.default)}`);
      else { params.push(`${name}=_rt.MISSING`); lateDefaults.push([name, p.default]); }
    }
    this.emit("");
    this.emit(`def ${sig.pyName}(${params.join(", ")}):`);
    this.ind++;
    if (d.globals?.size) this.emit(`global ${[...d.globals].join(", ")}`);
    if (d.nonlocals?.size) this.emit(`nonlocal ${[...d.nonlocals].join(", ")}`);
    for (const [n, def] of lateDefaults) this.emit(`if ${n} is _rt.MISSING: ${n} = ${this.ex(def)}`);
    const hasValue = prune(sig.ret).k !== "unit" && !d.implicitOk;
    if (d.usesTry) { this.emit("try:"); this.ind++; }
    if ("stmts" in d.body) this.block(d.body, hasValue ? RETURN : NONE);
    else {
      this.curLine = d.body.line;
      this.value(d.body, hasValue ? RETURN : NONE);
    }
    if (d.implicitOk) this.emit("return _rt.Ok(None)");
    if (d.usesTry) {
      this.ind--;
      this.emit("except _rt.Bail as _b:");
      this.emit("    return _b.v");
    }
    this.ind--;
  }

  // ---------- statements ----------
  block(b: A.Block, dest: Dest) {
    const before = this.lines.length;
    b.stmts.forEach((s, i) => {
      const last = i === b.stmts.length - 1;
      if (last && dest.k !== "none" && s.k === "expr") { this.curLine = s.line; this.value(s.expr, dest); }
      else this.stmt(s);
    });
    if (this.lines.length === before) this.emit("pass");
  }

  /** Emit code that computes `e` and delivers it to `dest`. */
  value(e: A.Expr, dest: Dest) {
    if (e.k === "if" && !this.isTernary(e)) return this.emitIf(e, dest);
    if (e.k === "match") return this.emitMatch(e, dest);
    const v = this.ex(e);
    if (dest.k === "return") this.emit(`return ${v}`);
    else if (dest.k === "assign") this.emit(`${dest.target} = ${v}`);
    else this.emit(v);
  }

  stmt(s: A.Stmt) {
    this.curLine = s.line;
    switch (s.k) {
      case "expr":
        if (s.expr.k === "if") return this.emitIf(s.expr, NONE);
        if (s.expr.k === "match") return this.emitMatch(s.expr, NONE);
        return this.emit(this.ex(s.expr));
      case "let": return this.assignTo(this.targetPat(s.target), s.value, s.target.k === "ptuple");
      case "assign": {
        if (s.op === "=" && (s.target.k === "name" || s.target.k === "tuple")) {
          const t = s.target.k === "name" ? pyName(s.target) : s.target.items.map((i) => (i.k === "name" ? pyName(i) : this.ex(i))).join(", ");
          return this.assignTo(t, s.value, s.target.k === "tuple");
        }
        const tgt = this.lvalue(s.target);
        if (s.op === "=") return this.assignTo(tgt, s.value, false);
        return this.emit(`${tgt} ${s.op} ${this.ex(s.value)}`);
      }
      case "while":
        this.emit(`while ${this.ex(s.cond)}:`);
        this.ind++; this.block(s.body, NONE); this.ind--;
        return;
      case "for":
        this.emit(`for ${this.targetPat(s.target)} in ${this.iter(s.iter)}:`);
        this.ind++; this.block(s.body, NONE); this.ind--;
        return;
      case "return":
        if (!s.value) return this.emit("return");
        return this.value(s.value, RETURN);
      case "break": return this.emit("break");
      case "continue": return this.emit("continue");
      case "pass": return this.emit("pass");
      case "assert": {
        const text = JSON.stringify(sourceText(this.prog.src, s.cond));
        return this.emit(`if not ${this.ex(s.cond)}: _rt.assert_fail(${text}${s.msg ? ", " + this.ex(s.msg) : ""})`);
      }
      case "fndecl": return this.emitFn(s.decl);
    }
  }

  assignTo(target: string, value: A.Expr, isTuple: boolean) {
    if ((value.k === "if" && !this.isTernary(value)) || value.k === "match") {
      if (!isTuple) return this.value(value, { k: "assign", target });
      const t = this.fresh();
      this.value(value, { k: "assign", target: t });
      return this.emit(`${target} = ${t}`);
    }
    this.emit(`${target} = ${this.ex(value)}`);
  }

  lvalue(e: A.Expr): string {
    if (e.k === "name") return pyName(e);
    return this.ex(e);
  }

  targetPat(p: A.Pattern): string {
    switch (p.k) {
      case "pbind": return pyId(p.name);
      case "pwild": return "_";
      case "ptuple": return p.els.map((x) => (x.k === "ptuple" ? `(${this.targetPat(x)})` : this.targetPat(x))).join(", ");
      default: return this.fail(p, "unsupported assignment target");
    }
  }

  /** Iterables: use Python's lazy forms directly in loops. */
  iter(e: A.Expr): string {
    if (e.k === "range") return `range(${this.ex(e.lo)}, ${e.inclusive ? this.plusOne(e.hi) : this.ex(e.hi)})`;
    if (e.k === "call" && e.resolved?.kind === "builtin") {
      const b = BUILTINS[e.resolved.builtin];
      if (b.lazy) return this.fill(b.lazy, e.resolved.args);
    }
    return this.ex(e);
  }

  plusOne(e: A.Expr): string {
    if (e.k === "int") return String(Number(e.value) + 1);
    return `${this.ex(e)} + 1`;
  }

  // ---------- if / match ----------
  isPureBlock(b: A.Block): boolean {
    return b.stmts.length === 1 && b.stmts[0].k === "expr" && this.isPureExpr(b.stmts[0].expr);
  }
  isPureExpr(e: A.Expr): boolean {
    if (e.k === "match") return false;
    if (e.k === "if") return this.isTernary(e);
    return true;
  }
  isTernary(e: Extract<A.Expr, { k: "if" }>): boolean {
    return !!e.else && e.branches.every((b) => this.isPureBlock(b.body)) && this.isPureBlock(e.else);
  }

  emitIf(e: Extract<A.Expr, { k: "if" }>, dest: Dest) {
    e.branches.forEach((br, i) => {
      this.curLine = br.cond.line;
      this.emit(`${i === 0 ? "if" : "elif"} ${this.ex(br.cond)}:`);
      this.ind++; this.block(br.body, dest); this.ind--;
    });
    if (e.else) {
      this.emit("else:");
      this.ind++; this.block(e.else, dest); this.ind--;
    }
  }

  emitMatch(e: Extract<A.Expr, { k: "match" }>, dest: Dest) {
    let subj: string;
    if (e.subject.k === "name") subj = this.ex(e.subject);
    else { subj = this.fresh("_m"); this.emit(`${subj} = ${this.ex(e.subject)}`); }
    this.emit(`match ${subj}:`);
    this.ind++;
    for (const arm of e.arms) {
      this.curLine = arm.pos.line;
      const guards: string[] = [];
      const p = this.pattern(arm.pattern, guards);
      if (arm.guard) guards.push(this.ex(arm.guard));
      this.emit(`case ${p}${guards.length ? " if " + guards.join(" and ") : ""}:`);
      this.ind++; this.block(arm.body, dest); this.ind--;
    }
    this.ind--;
  }

  pattern(p: A.Pattern, guards: string[]): string {
    switch (p.k) {
      case "pwild": return "_";
      case "pbind": return pyId(p.name);
      case "plit": return this.ex(p.value).replace(/^\((-\S+)\)$/, "$1");
      case "pnone": return "None";
      case "psome": {
        const inner = p.inner;
        if (inner.k === "pbind") { guards.push(`${pyId(inner.name)} is not None`); return pyId(inner.name); }
        if (inner.k === "pwild") { const t = this.fresh("_s"); guards.push(`${t} is not None`); return t; }
        return this.pattern(inner, guards);
      }
      case "pok": return `_rt.Ok(${this.pattern(p.inner, guards)})`;
      case "perr": return `_rt.Err(${this.pattern(p.inner, guards)})`;
      case "pctor": {
        const name = p.variant?.pyName ?? pyId(p.name);
        return `${name}(${p.args.map((a) => this.pattern(a, guards)).join(", ")})`;
      }
      case "ptuple": return `(${p.els.map((x) => this.pattern(x, guards)).join(", ")})`;
      case "por": return p.alts.map((x) => this.pattern(x, guards)).join(" | ");
    }
  }

  // ---------- expressions ----------
  fill(tpl: string, args: A.Expr[]): string {
    return tpl.replace(/\{(\d+)\}/g, (_, i) => this.ex(args[Number(i)]));
  }

  ex(e: A.Expr): string {
    switch (e.k) {
      case "int": return e.value;
      case "float": return e.value;
      case "bool": return e.value ? "True" : "False";
      case "none": return "None";
      case "str": {
        if (e.parts.every((p) => typeof p === "string")) return pyStr(e.parts.join(""));
        const pieces = e.parts.map((p, i) => {
          if (typeof p === "string") return p === "" ? "" : pyStr(p);
          const spec = e.specs?.[i];
          if (spec) return `format(${this.ex(p)}, ${pyStr(spec)})`;
          const t = p.ty ? prune(p.ty) : undefined;
          return t?.k === "str" ? this.ex(p) : `_rt.show(${this.ex(p)})`;
        }).filter((x) => x !== "");
        if (pieces.length === 1 && typeof e.parts.find((p) => p !== "") !== "string" && !pieces[0].startsWith("_rt.show")) return `_rt.show(${pieces[0]})`;
        return pieces.length === 1 ? pieces[0] : `(${pieces.join(" + ")})`;
      }
      case "name": return this.nameRef(e);
      case "list": return `[${e.items.map((i) => this.ex(i)).join(", ")}]`;
      case "map": return `{${e.entries.map(([k, v]) => `${this.ex(k)}: ${this.ex(v)}`).join(", ")}}`;
      case "tuple":
        if (e.items.length === 0) return "None";
        return `(${e.items.map((i) => this.ex(i)).join(", ")}${e.items.length === 1 ? "," : ""})`;
      case "call": return this.call(e);
      case "member": {
        if (e.memberKind === "module" && e.moduleRef) return this.refToPy(e.moduleRef);
        const obj = this.ex(e.obj);
        if (e.memberKind === "dyn" && /^(?:False|None|True|and|as|assert|async|await|break|class|continue|def|del|elif|else|except|finally|for|from|global|if|import|in|is|lambda|nonlocal|not|or|pass|raise|return|try|while|with|yield)$/.test(e.name)) {
          return `getattr(${obj}, ${JSON.stringify(e.name)})`;
        }
        return `${obj}.${e.pyName ?? e.name}`;
      }
      case "index": return `${this.ex(e.obj)}[${this.ex(e.index)}]`;
      case "slice": return `${this.ex(e.obj)}[${e.lo ? this.ex(e.lo) : ""}:${e.hi ? this.ex(e.hi) : ""}]`;
      case "binary": return this.binary(e);
      case "unary": return e.op === "not" ? `(not ${this.ex(e.expr)})` : `(-${this.ex(e.expr)})`;
      case "lambda": {
        this.lambdaDepth++;
        const ps = e.params.map((p) => pyId(p.name));
        for (const c of e.captures ?? []) if (!ps.includes(c)) ps.push(`${c}=${c}`);
        const body = this.ex(e.body);
        this.lambdaDepth--;
        return `(lambda${ps.length ? " " + ps.join(", ") : ""}: ${body})`;
      }
      case "try": return e.tryKind === "res" ? `_rt.try_res(${this.ex(e.expr)})` : `_rt.try_opt(${this.ex(e.expr)})`;
      case "unwrap": return e.tryKind === "res" ? `_rt.unwrap_res(${this.ex(e.expr)})` : `_rt.unwrap_opt(${this.ex(e.expr)})`;
      case "if": {
        if (this.isTernary(e)) {
          let out = this.ex(onlyExpr(e.else!));
          for (let i = e.branches.length - 1; i >= 0; i--) out = `(${this.ex(onlyExpr(e.branches[i].body))} if ${this.ex(e.branches[i].cond)} else ${out})`;
          return out;
        }
        return this.hoist(e);
      }
      case "match": return this.hoist(e);
      case "comp": {
        const head = e.isMap ? `${this.ex(e.elem)}: ${this.ex(e.value!)}` : this.ex(e.elem);
        const tail = `for ${this.targetPat(e.target)} in ${this.iter(e.iter)}${e.cond ? " if " + this.ex(e.cond) : ""}`;
        return e.isMap ? `{${head} ${tail}}` : `[${head} ${tail}]`;
      }
      case "range": return `list(range(${this.ex(e.lo)}, ${e.inclusive ? this.plusOne(e.hi) : this.ex(e.hi)}))`;
      case "cast": {
        const t = e.target ? prune(e.target) : undefined;
        const kinds: Record<string, string> = { int: "int", float: "float", str: "str", bool: "bool", list: "list", map: "map" };
        const kind = t ? kinds[t.k] : undefined;
        if (!kind) return this.ex(e.expr);
        return `_rt.cast(${this.ex(e.expr)}, "${kind}", ${JSON.stringify(exprTypeText(e.type))})`;
      }
    }
  }

  /** A block-form if/match used inside a larger expression: compute it first into a temp. */
  hoist(e: A.Expr): string {
    if (this.lambdaDepth > 0) this.fail(e, "a multi-line if/match can't be used inside a lambda", "move it into a named fn");
    const t = this.fresh();
    this.value(e, { k: "assign", target: t });
    return t;
  }

  nameRef(e: Extract<A.Expr, { k: "name" }>): string {
    if (!e.ref) return pyId(e.name);
    return this.refToPy(e.ref);
  }

  refToPy(r: A.NameRef): string {
    switch (r.kind) {
      case "var": case "fn": case "record": return r.pyName;
      case "const": return r.py;
      case "variant": return r.nullary ? `${r.pyName}()` : r.pyName;
      case "builtin": {
        const b = BUILTINS[r.builtin];
        const n = (b.sig.match(/\(([^)]*)\)/)?.[1] ?? "").split(",").filter((s) => s.trim()).length;
        const names = Array.from({ length: n }, (_, i) => `_a${i}`);
        const body = b.py.replace(/\{(\d+)\}/g, (_, i) => `_a${i}`).replace("{*}", names.join(", "));
        return `(lambda ${names.join(", ")}: ${body})`;
      }
    }
  }

  args(args: A.Arg[], leading: string[] = []): string {
    const out = [...leading];
    for (const a of args) out.push(a.name ? `${pyId(a.name)}=${this.ex(a.value)}` : this.ex(a.value));
    return out.join(", ");
  }

  call(e: Extract<A.Expr, { k: "call" }>): string {
    const r = e.resolved;
    const callee = e.callee;
    switch (r?.kind) {
      case "builtin": {
        if (r.print) return `_rt.tsa_print(${r.args.map((a) => this.ex(a)).join(", ")})`;
        return this.fill(BUILTINS[r.builtin].py, r.args);
      }
      case "method": {
        const m = callee as Extract<A.Expr, { k: "member" }>;
        return `${this.ex(m.obj)}.${r.pyName}(${this.args(e.args)})`;
      }
      case "ufcs": {
        const m = callee as Extract<A.Expr, { k: "member" }>;
        return `${r.pyName}(${this.args(e.args, [this.ex(m.obj)])})`;
      }
      case "fn": return `${r.pyName}(${this.args(e.args)})`;
      case "ctor": {
        const parts: string[] = [];
        for (const a of e.args) parts.push(a.name ? `${pyAttr(a.name)}=${this.ex(a.value)}` : this.ex(a.value));
        return `${r.pyName}(${parts.join(", ")})`;
      }
      case "with": {
        const m = callee as Extract<A.Expr, { k: "member" }>;
        const parts = e.args.filter((a) => a.name).map((a) => `${pyAttr(a.name!)}=${this.ex(a.value)}`);
        return `_rt.replace(${this.ex(m.obj)}${parts.length ? ", " + parts.join(", ") : ""})`;
      }
      case "dyn": case "value": default:
        return `${this.ex(callee)}(${this.args(e.args)})`;
    }
  }

  binary(e: Extract<A.Expr, { k: "binary" }>): string {
    if ((e.op === "==" || e.op === "!=") && (e.left.k === "none" || e.right.k === "none")) {
      const other = e.left.k === "none" ? e.right : e.left;
      return `(${this.ex(other)} ${e.op === "==" ? "is" : "is not"} None)`;
    }
    if (e.op === "??") {
      const t = this.fresh();
      const lt = e.left.ty ? prune(e.left.ty) : undefined;
      if (lt?.k === "res") return `(${t}.value if isinstance((${t} := ${this.ex(e.left)}), _rt.Ok) else ${this.ex(e.right)})`;
      return `(${t} if (${t} := ${this.ex(e.left)}) is not None else ${this.ex(e.right)})`;
    }
    return `(${this.ex(e.left)} ${e.op} ${this.ex(e.right)})`;
  }
}

function pyName(e: Extract<A.Expr, { k: "name" }>): string {
  return e.ref && (e.ref.kind === "var" || e.ref.kind === "fn") ? e.ref.pyName : pyId(e.name);
}

function onlyExpr(b: A.Block): A.Expr {
  return (b.stmts[0] as Extract<A.Stmt, { k: "expr" }>).expr;
}

function isLiteral(e: A.Expr): boolean {
  if (e.k === "int" || e.k === "float" || e.k === "bool" || e.k === "none") return true;
  if (e.k === "str") return e.parts.every((p) => typeof p === "string");
  if (e.k === "unary" && e.op === "-") return isLiteral(e.expr);
  if (e.k === "name" && e.ref?.kind === "const") return true;
  return false;
}

function pyStr(s: string): string {
  return JSON.stringify(s);
}

function sourceText(src: string, e: A.Expr): string {
  const line = src.split("\n")[e.line - 1] ?? "";
  if (e.end > e.col) return line.slice(e.col - 1, e.end - 1);
  return exprText(e);
}

function exprTypeText(t: A.TypeExpr): string {
  switch (t.k) {
    case "tname": return t.name + (t.args.length ? `[${t.args.map(exprTypeText).join(", ")}]` : "");
    case "tlist": return `[${exprTypeText(t.el)}]`;
    case "tmap": return `{${exprTypeText(t.key)}: ${exprTypeText(t.val)}}`;
    case "ttuple": return `(${t.els.map(exprTypeText).join(", ")})`;
    case "topt": return exprTypeText(t.inner) + "?";
    case "tres": return `${exprTypeText(t.ok)}!${exprTypeText(t.err)}`;
    case "tfn": return `fn(${t.params.map(exprTypeText).join(", ")}) -> ${exprTypeText(t.ret)}`;
  }
}

